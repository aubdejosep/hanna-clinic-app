// Turns the scraped Services list (tools/medical-records-download/services.mjs) into SQL.
//
//   npm run import:services -- --services path/to/services.json
//
// Writes data/import-services.sql (git-ignored). Load with:
//   npx wrangler d1 execute hanna-clinic --local  --file data/import-services.sql   (then --remote)
//
// Adds every service with its category, price, description, Active and "Featured for online booking"
// switches, and variations. A service whose name is already on the Services page is left as it is
// (and listed in the output), so running it twice adds nothing twice.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const args = Object.fromEntries(
  process.argv.slice(2).reduce((pairs, arg, i, all) => (arg.startsWith('--') ? [...pairs, [arg.slice(2), all[i + 1]]] : pairs), []),
)
if (!args.services) {
  console.error('Usage: npm run import:services -- --services <services.json>')
  process.exit(1)
}
const tidy = (v) => String(v ?? '').replace(/\s+/g, ' ').trim()
const cents = (v) => {
  const n = Number(String(v ?? '').replace(/[₱,\s]/g, ''))
  return Number.isFinite(n) && n >= 0 ? Math.round(n * 100) : 0
}
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)

const services = JSON.parse(readFileSync(args.services, 'utf8'))
const stamp = new Date().toISOString()
const sql = [`-- Generated by scripts/import-services.mjs on ${stamp}.`]
const seen = new Set()
let variations = 0
for (const s of services) {
  const name = tidy(s.name).slice(0, 60)
  if (!name || seen.has(name.toLowerCase())) continue
  seen.add(name.toLowerCase())
  const category = tidy(s.category).slice(0, 50) || 'Other'
  sql.push(`INSERT OR IGNORE INTO service_categories (name) VALUES (${q(category)});`)
  sql.push(`INSERT INTO services (name, description, price_cents, category_id, active, featured_online, created_at)
SELECT ${q(name)}, ${q(tidy(s.description).slice(0, 300) || null)}, ${cents(s.price)}, (SELECT id FROM service_categories WHERE name = ${q(category)} COLLATE NOCASE), ${s.active === false ? 0 : 1}, ${s.featuredOnline ? 1 : 0}, ${q(stamp)}
WHERE NOT EXISTS (SELECT 1 FROM services WHERE name = ${q(name)} COLLATE NOCASE AND deleted_at IS NULL);`)
  ;(s.variations || []).forEach((v, i) => {
    variations++
    sql.push(`INSERT INTO service_variations (service_id, name, description, price_cents, sort)
SELECT id, ${q(tidy(v.name).slice(0, 60) || `Option ${i + 1}`)}, ${q(tidy(v.description).slice(0, 300) || null)}, ${cents(v.price)}, ${i}
FROM services WHERE name = ${q(name)} COLLATE NOCASE AND created_at = ${q(stamp)} AND deleted_at IS NULL;`)
  })
}
sql.push(`INSERT INTO audit_log (actor, action, entity, detail) VALUES ('import', 'legacy_import', 'services', ${q(JSON.stringify({ services: seen.size, variations }))});`, '')
mkdirSync('data', { recursive: true })
writeFileSync('data/import-services.sql', sql.join('\n'))
console.log(`${seen.size} services and ${variations} variations. Wrote data/import-services.sql
Services already on the Services page (same name) are left as they are.`)
