// Links the uploaded photos to their medical record entries in the app.
//
//   npm run import:photos -- --dir ..\tools\medical-records-download\output-photos
//   npx wrangler d1 execute hanna-clinic --remote --file data/import-photos.sql
//
// Only photos listed in <dir>\uploaded.txt (already in storage) are linked. Safe to run again: it
// replaces what an earlier run linked. Run it again after re-running the medical records import
// (that import replaces the records, so the links have to be made again). Add --local to use
// uploaded-local.txt (the local test copy).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const args = Object.fromEntries(process.argv.slice(2).reduce((pairs, a, i, all) => (a.startsWith('--') ? [...pairs, [a.slice(2), all[i + 1]?.startsWith('--') ? true : all[i + 1] ?? true]] : pairs), []))
if (!args.dir || args.dir === true) { console.error('Usage: npm run import:photos -- --dir <output-photos folder> [--local]'); process.exit(1) }
const DIR = resolve(args.dir)
const uploadedFile = join(DIR, args.local ? 'uploaded-local.txt' : 'uploaded.txt')
const uploaded = new Set(existsSync(uploadedFile) ? readFileSync(uploadedFile, 'utf8').split('\n').filter(Boolean) : [])
const photos = readFileSync(join(DIR, 'photos.jsonl'), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)).filter((p) => uploaded.has(p.key))
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const sql = [`-- Generated by scripts/import-photos.mjs on ${new Date().toISOString()}.`, "DELETE FROM medical_images WHERE source = 'legacy';"]
for (const p of photos) {
  // The entry: same record (zip/pdf, as the records import saved it) and the same position.
  sql.push(`INSERT OR IGNORE INTO medical_images (record_id, entry_id, pet_id, key, bytes, width, height, sort, source)
SELECT m.id, e.id, m.pet_id, ${q(p.key)}, ${p.bytes || 'NULL'}, ${p.width || 'NULL'}, ${p.height || 'NULL'}, ${p.n}, 'legacy'
FROM medical_records m JOIN medical_entries e ON e.record_id = m.id AND e.sort = ${p.entry} AND e.deleted_at IS NULL
WHERE m.source = 'legacy' AND m.legacy_file = ${q(`${p.zip}/${p.file}`)} AND m.deleted_at IS NULL LIMIT 1;`)
}
mkdirSync('data', { recursive: true })
writeFileSync('data/import-photos.sql', `${sql.join('\n')}\n`)
console.log(`Wrote data/import-photos.sql: ${photos.length} photos to link${uploaded.size ? '' : ' (nothing uploaded yet: run upload:photos first)'}.`)
