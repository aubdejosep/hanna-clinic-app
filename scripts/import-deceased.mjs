// Marks pets as passed away from the old system's Masterlist ▸ Deceased Pets export.
//
//   npm run import:deceased -- --csv path/to/masterlist_YYYY-MM-DD.csv [--date YYYY-MM-DD]
//
// Writes data/import-deceased.sql (git-ignored). Load with:
//   npx wrangler d1 execute hanna-clinic --local  --file data/import-deceased.sql   (then --remote)
//
// Pets are matched by the owner's customer number and the pet's name. The old export has no date of
// death, so "Passed Away On" is set to --date (default: the date in the file name, else today); it can
// be corrected on the pet's page. A pet already marked keeps its date. Their open future bookings
// are cancelled ("Pet passed away"). Running it twice changes nothing more.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { basename } from 'node:path'

const args = Object.fromEntries(
  process.argv.slice(2).reduce((pairs, arg, i, all) => (arg.startsWith('--') ? [...pairs, [arg.slice(2), all[i + 1]]] : pairs), []),
)
if (!args.csv) {
  console.error('Usage: npm run import:deceased -- --csv <masterlist.csv> [--date YYYY-MM-DD]')
  process.exit(1)
}
function parseCsv(text) {
  const rows = []
  let row = []; let field = ''; let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) { if (c === '"' && text[i + 1] === '"') { field += '"'; i++ } else if (c === '"') quoted = false; else field += c }
    else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(field); rows.push(row); row = []; field = '' }
    else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  return rows.filter((r) => r.some((f) => f.trim()))
}
const q = (v) => `'${String(v).replace(/'/g, "''")}'`
const tidy = (v) => String(v ?? '').replace(/\s+/g, ' ').trim()
const date = args.date || basename(args.csv).match(/\d{4}-\d{2}-\d{2}/)?.[0] || new Date(Date.now() + 8 * 3600e3).toISOString().slice(0, 10)
if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) { console.error('--date must look like 2026-11-11'); process.exit(1) }

const [head, ...rows] = parseCsv(readFileSync(args.csv, 'utf8').replace(/^﻿/, ''))
const col = (n) => head.findIndex((h) => tidy(h).toLowerCase() === n)
const iPet = col('pet name')
const iCust = col('customer number')
if (iPet < 0 || iCust < 0) { console.error('Expected "Pet Name" and "Customer Number" columns.'); process.exit(1) }

const now = new Date().toISOString()
const sql = [`-- Generated by scripts/import-deceased.mjs on ${now}. Passed away on (or before) ${date}.`]
let n = 0
for (const r of rows) {
  const pet = tidy(r[iPet]); const cust = tidy(r[iCust])
  if (!pet || !/^C\d+$/.test(cust)) continue
  const match = `SELECT p.id FROM pets p JOIN owners o ON o.id = p.owner_id WHERE o.customer_no = ${q(cust)} AND TRIM(p.name) = ${q(pet)} COLLATE NOCASE AND p.deleted_at IS NULL`
  sql.push(`UPDATE appointments SET status = 'cancelled', cancelled_at = ${q(now)}, cancel_reason = 'Pet passed away', updated_at = ${q(now)}
  WHERE pet_id IN (${match}) AND status IN ('pending', 'accepted') AND day >= ${q(date)} AND deleted_at IS NULL;`)
  sql.push(`UPDATE pets SET deceased_on = ${q(date)}, updated_at = ${q(now)} WHERE deceased_on IS NULL AND id IN (${match});`)
  n++
}
sql.push(`INSERT INTO audit_log (actor, action, entity, entity_id, detail) VALUES ('import', 'import_deceased', 'pet', NULL, ${q(JSON.stringify({ pets: n, date }))});`)
mkdirSync('data', { recursive: true })
writeFileSync('data/import-deceased.sql', `${sql.join('\n')}\n`)
console.log(`Wrote data/import-deceased.sql: ${n} pets, passed away on or before ${date}.`)
