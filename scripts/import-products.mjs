// Turns the old system's inventory export (Inventory ▸ Export, the *_products.csv file) into the
// Product List: names, categories, prices and costs. Stock is not imported: the old numbers aren't
// trusted, so the first Stock Count (the baseline) sets it.
//
//   npm run import:products -- --csv path/to/inventory_..._products.csv
//
// Writes data/import-products.sql (git-ignored). Load with:
//   npx wrangler d1 execute hanna-clinic --local  --file data/import-products.sql   (then --remote)
//
// Vaccines and services in the export are left out: they're picked from the Services list
// (e.g. VACCINE · ANTI RABIES). A name already on the list is skipped, so running it twice is safe.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const args = Object.fromEntries(
  process.argv.slice(2).reduce((pairs, arg, i, all) => (arg.startsWith('--') ? [...pairs, [arg.slice(2), all[i + 1]]] : pairs), []),
)
if (!args.csv) {
  console.error('Usage: npm run import:products -- --csv <inventory_..._products.csv>')
  process.exit(1)
}

// A small CSV reader: quoted fields, doubled quotes, commas and line breaks inside quotes.
function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++ } else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field); rows.push(row); row = []; field = ''
    } else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  return rows.filter((r) => r.some((f) => f.trim()))
}

const CATEGORY = {
  'vitamins / supplement': 'Vitamins & Supplements', medicine: 'Medicine', shampoo: 'Shampoo', 'medicated soap': 'Medicated Soap',
  'ear drops': 'Ear & Eye Drops', 'eye drop': 'Ear & Eye Drops', accessories: 'Accessories',
}
const SKIP = new Set(['vaccine', 'services'])
const tidy = (v) => String(v ?? '').replace(/\s+/g, ' ').trim()
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)

const [head, ...rows] = parseCsv(readFileSync(args.csv, 'utf8').replace(/^﻿/, ''))
const col = (name) => head.findIndex((h) => tidy(h).toLowerCase() === name)
const iName = col('product name')
const iVar = col('variations')
const iCat = col('category')
const iPrice = col('price')
const iCost = col('cost price')
const money = (v) => { const n = Number(String(v ?? '').replace(/[₱,\s]/g, '')); return Number.isFinite(n) && n > 0 ? Math.round(n * 100) : null }
if (iName < 0) { console.error('No "Product Name" column found. Is this the *_products.csv file?'); process.exit(1) }

const sql = [`-- Generated by scripts/import-products.mjs on ${new Date().toISOString()}.`]
const seen = new Set()
const skipped = []
for (const r of rows) {
  const raw = tidy(r[iCat]).toLowerCase()
  const variation = tidy(r[iVar]).replace(/^—$/, '')
  const name = tidy(`${tidy(r[iName])}${variation ? ` ${variation}` : ''}`).slice(0, 60)
  if (!name) continue
  if (SKIP.has(raw)) { skipped.push(`${name} (${tidy(r[iCat])})`); continue }
  if (seen.has(name.toLowerCase())) continue
  seen.add(name.toLowerCase())
  const category = CATEGORY[raw] || (raw ? tidy(r[iCat]).replace(/\b\w/g, (c) => c.toUpperCase()) : 'Other')
  sql.push(`INSERT OR IGNORE INTO products (branch_id, name, category, source) VALUES (1, ${q(name)}, ${q(category)}, 'inventory');`)
  // Prices from the old system, per item as it was sold there; check the unit at the first stock count.
  const price = iPrice >= 0 ? money(r[iPrice]) : null
  const cost = iCost >= 0 ? money(r[iCost]) : null
  if (price != null || cost != null) sql.push(`UPDATE products SET price_cents = COALESCE(price_cents, ${price ?? 'NULL'}), cost_cents = COALESCE(cost_cents, ${cost ?? 'NULL'}) WHERE branch_id = 1 AND name = ${q(name)} COLLATE NOCASE AND deleted_at IS NULL;`)
}
mkdirSync('data', { recursive: true })
writeFileSync('data/import-products.sql', `${sql.join('\n')}\n`)
console.log(`Wrote data/import-products.sql: ${seen.size} medicines and products.`)
if (skipped.length) console.log(`Left out (pick these from Services): ${skipped.join(', ')}`)
